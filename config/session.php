<?php
/**
 * ملف بدء الجلسة (Session)
 * 
 * الجلسة (Session) هي طريقة لتخزين معلومات المستخدم أثناء تصفحه للموقع
 * تسمح بتذكر المستخدم بين الصفحات المختلفة
 * 
 * كيف تعمل؟
 * 1. عند بدء الجلسة، الخادم يرسل ملف تعريف (Cookie) للمتصفح
 * 2. في كل طلب جديد، المتصفح يرسل ملف التعريف
 * 3. الخادم يقرأ ملف التعريف ويعيد بناء بيانات الجلسة
 */

// التحقق من حالة الجلسة
// PHP_SESSION_NONE يعني أن الجلسة لم تبدأ بعد
if (session_status() === PHP_SESSION_NONE) {
    // بدء الجلسة
    // بعد هذا السطر، يمكننا استخدام $_SESSION
    session_start();
}
?>
